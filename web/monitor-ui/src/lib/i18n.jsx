const I18nContext = createContext(null);

function normalizeLanguage(value) {
  return languageOptions.some((option) => option.value === value) ? value : "zh-CN";
}

export function currentLanguage() {
  if (typeof window === "undefined") {
    return "zh-CN";
  }
  return normalizeLanguage(window.localStorage.getItem(LANGUAGE_KEY));
}

export function translate(language, key, values = {}) {
  const dictionary = dictionaries[normalizeLanguage(language)] || dictionaries["zh-CN"];
  const fallback = dictionaries.en[key] || key;
  const template = dictionary[key] || fallback;
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(() => currentLanguage());

  useEffect(() => {
    document.documentElement.lang = language === "en" ? "en" : "zh-CN";
  }, [language]);

  const value = useMemo(() => {
    const setLanguage = (nextLanguage) => {
      const normalized = normalizeLanguage(nextLanguage);
      window.localStorage.setItem(LANGUAGE_KEY, normalized);
      setLanguageState(normalized);
    };
    return {
      language,
      setLanguage,
      t: (key, values) => translate(language, key, values),
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    return {
      language: "zh-CN",
      setLanguage: () => {},
      t: (key, values) => translate("zh-CN", key, values),
    };
  }
  return value;
}
